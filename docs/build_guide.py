"""
Builds the user guide's generated parts: docs/snippets.md with a picture of
every built-in snippet (docs/images/snippets/*.svg), and, when Playwright is
installed, the designer screenshots of docs/getting-started.md and the README (docs/images/*.png):

    python docs/build_guide.py
    python docs/build_guide.py --no-screenshots
"""

import argparse
import json
import pathlib
import sys
import tempfile
import threading

DOCS = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(DOCS.parent / 'src'))

import pyxelwidgets.designer  # noqa: E402

ORDER = ['Drums', 'Sequencing', 'Melody', 'Chords', 'Clips', 'Mixing', 'Transport', 'Effects', 'Generative']


def svg(preview, cell = 12, gap = 2) -> str:
    """A snippet's picture: its pads as rounded squares, dark where nothing is lit."""
    rows, columns = len(preview), len(preview[0])
    width, height = columns * (cell + gap) + gap, rows * (cell + gap) + gap
    pads = ''.join(f'<rect x="{gap + x * (cell + gap)}" y="{gap + y * (cell + gap)}" width="{cell}" height="{cell}" rx="2" fill="{color or "#24272e"}"/>'
                   for y, row in enumerate(preview) for x, color in enumerate(row))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">'
            f'<rect width="{width}" height="{height}" rx="4" fill="#121418"/>{pads}</svg>\n')


def snippets_markdown() -> tuple:
    """(docs/snippets.md's text, {picture file name: SVG})."""
    entries = pyxelwidgets.designer.snippets(pathlib.Path('/nonexistent'))
    pictures = {}
    lines = ['# Snippets', '',
             'Ready-made pieces in the designer\'s **Snippets** tab (next to Widgets): widgets with their links',
             'and messages. Pick a size there, then click one to add it at the corner of the selected group, or',
             'drag it onto the grid. Messages go to an output of the same kind when the layout has one; otherwise',
             'the snippet adds its own. Select widgets and press *Save selection* to make snippets of your own.', '',
             'Sizes are width x height: 8x2 is two rows of eight pads, 2x8 two columns.', '',
             '*Generated by `python docs/build_guide.py` from `src/pyxelwidgets/designer/snippets`.*', '']
    categories = sorted({entry['category'] for entry in entries}, key = lambda name: (ORDER.index(name) if name in ORDER else len(ORDER), name))
    for category in categories:
        lines += [f'## {category}', '']
        for entry in sorted((e for e in entries if e['category'] == category), key = lambda e: (-e['size'][0] * e['size'][1], e['title'])):
            pictures[f'{entry["id"]}.svg'] = svg(entry['preview'])
            outputs = sorted({output['type'] for output in entry['snippet'].get('outputs') or []})
            lines += [f'### {entry["title"]} ({entry["size"][0]}x{entry["size"][1]})', '',
                      f'![{entry["title"]}](images/snippets/{entry["id"]}.svg)', '', entry['doc'].rstrip('.') + '.', '']
            if outputs:
                lines += [f'Sends to: {", ".join(f"`{output}`" for output in outputs)}.', '']
    return '\n'.join(lines).rstrip() + '\n', pictures


def snippets_page() -> None:
    text, pictures = snippets_markdown()
    images = DOCS / 'images' / 'snippets'
    images.mkdir(parents = True, exist_ok = True)
    for name, picture in pictures.items():
        (images / name).write_text(picture)
    (DOCS / 'snippets.md').write_text(text)
    print(f'Wrote {DOCS / "snippets.md"} ({len(pictures)} snippets)')


