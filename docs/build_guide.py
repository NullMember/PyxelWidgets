def screenshots() -> None:
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        print('Playwright is not installed: screenshots skipped (pip install playwright && playwright install chromium)')
        return
    images = DOCS / 'images'
    with tempfile.TemporaryDirectory() as folder:
        server = pyxelwidgets.designer.serve(str(pathlib.Path(folder) / 'drums.json'), port = 0, connect = False,
                                             snippets = str(pathlib.Path(folder) / 'snippets'), dialogs = False)
        threading.Thread(target = server.serve_forever, daemon = True).start()
        url = f'http://127.0.0.1:{server.server_address[1]}/'
        try:
            with sync_playwright() as p:
                browser = p.chromium.launch()
                page = browser.new_page(viewport = {'width': 1280, 'height': 800})
                page.goto(url)
                page.wait_for_selector('#start')
                page.screenshot(path = str(images / 'start-window.png'))
                page.keyboard.press('Escape')
                page.evaluate("layout => fetch('/api/layout', {method: 'PUT', body: JSON.stringify(layout)})", GUIDE_LAYOUT)
                page.reload()
                page.wait_for_selector('#tree .node')
                page.click('#tree .node:has-text("pads")')
                page.wait_for_timeout(300)
                page.screenshot(path = str(images / 'properties.png'))
                page.click('.rule-summary li >> nth=0')
                page.wait_for_selector('#mapping-0-message-learn')
                page.screenshot(path = str(images / 'messages-window.png'))
                page.click('#rules-close')
                page.click('#mode-try')
                box = page.locator('.pad[data-x="1"][data-y="2"]').bounding_box()
                page.mouse.move(box['x'] + box['width'] / 2, box['y'] + box['height'] / 2, steps = 2)
                page.wait_for_selector('#pad-info:visible')
                page.screenshot(path = str(images / 'try-mode.png'))
                # The README's picture: the performance template playing
                page.set_viewport_size({'width': 1440, 'height': 860})
                page.evaluate("fetch('/api/new', {method: 'POST', body: JSON.stringify({template: 'performance'})})")
                page.reload()
                page.wait_for_selector('#tree .node')
                page.keyboard.press('Escape')
                page.click('#mode-try')
                for x, y in ((4, 0), (6, 0), (5, 1), (7, 1), (4, 2), (6, 3), (1, 1), (2, 2)):
                    page.evaluate("([x, y]) => fetch('/api/input', {method: 'POST', body: JSON.stringify({x, y, velocity: 1})})", [x, y])
                    page.evaluate("([x, y]) => fetch('/api/input', {method: 'POST', body: JSON.stringify({x, y, velocity: 0})})", [x, y])
                page.click('#play')
                page.wait_for_timeout(2500)
                page.screenshot(path = str(images / 'designer.png'))
                browser.close()
        finally:
            server.RequestHandlerClass.designer.close()
            server.shutdown()
            server.server_close()
    print(f'Wrote the screenshots to {images}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description = __doc__.strip().splitlines()[0])
    parser.add_argument('--no-screenshots', action = 'store_true')
    args = parser.parse_args()
    snippets_page()
    if not args.no_screenshots:
        screenshots()
