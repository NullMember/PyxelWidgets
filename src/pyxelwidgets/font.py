def _glyph(char: str) -> numpy.ndarray:
    rows = GLYPHS.get(char.upper(), GLYPHS['?'])
    # (x, y) with y from the bottom, like widget buffers
    return numpy.array([[row[x] == '#' for row in reversed(rows)] for x in range(len(rows[0]))], dtype = bool)

_CACHE = {}

def glyph(char: str) -> numpy.ndarray:
    """The bitmap of one character: bool array (width, 5)."""
    if char not in _CACHE:
        _CACHE[char] = _glyph(char)
    return _CACHE[char]

def text_width(text: str) -> int:
    return sum(glyph(char).shape[0] for char in text) + SPACING * max(len(text) - 1, 0)

def text_bitmap(text: str) -> numpy.ndarray:
    """``text`` as a bool array (width, 5); x from the left, y from the bottom."""
    bitmap = numpy.zeros((text_width(text), HEIGHT), dtype = bool)
    x = 0
    for char in text:
        bits = glyph(char)
        bitmap[x:x + bits.shape[0]] = bits
        x += bits.shape[0] + SPACING
    return bitmap
